-- YottaFlex Insurance Underwriting Platform
-- Consolidated schema evolution after the initial schema baseline.
-- Review the current database before applying. This script preserves rows.
-- It adds columns/relationships introduced during implementation.

BEGIN;

-- Endorsement activation tracking and payment association.
ALTER TABLE endorsements
    ADD COLUMN IF NOT EXISTS activated_at TIMESTAMPTZ;

ALTER TABLE payments
    ADD COLUMN IF NOT EXISTS endorsement_id VARCHAR(50);

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'payments_endorsement_id_fkey') THEN
        ALTER TABLE payments ADD CONSTRAINT payments_endorsement_id_fkey
            FOREIGN KEY (endorsement_id) REFERENCES endorsements(endorsement_id);
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_payments_endorsement_id
    ON payments(endorsement_id) WHERE endorsement_id IS NOT NULL;

-- Link renewal offers to their renewal quotes and payments.
ALTER TABLE renewals
    ADD COLUMN IF NOT EXISTS renewed_policy_id VARCHAR(20);

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'renewals_renewed_policy_id_fkey') THEN
        ALTER TABLE renewals ADD CONSTRAINT renewals_renewed_policy_id_fkey
            FOREIGN KEY (renewed_policy_id) REFERENCES policies(policy_id);
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_renewals_renewed_policy_id
    ON renewals(renewed_policy_id) WHERE renewed_policy_id IS NOT NULL;

ALTER TABLE quotes
    ADD COLUMN IF NOT EXISTS renewal_id VARCHAR(50);

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'quotes_renewal_id_fkey') THEN
        ALTER TABLE quotes ADD CONSTRAINT quotes_renewal_id_fkey
            FOREIGN KEY (renewal_id) REFERENCES renewals(renewal_id);
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_quotes_renewal_id
    ON quotes(renewal_id) WHERE renewal_id IS NOT NULL;

ALTER TABLE payments
    ADD COLUMN IF NOT EXISTS renewal_id VARCHAR(50);

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'payments_renewal_id_fkey') THEN
        ALTER TABLE payments ADD CONSTRAINT payments_renewal_id_fkey
            FOREIGN KEY (renewal_id) REFERENCES renewals(renewal_id);
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_payments_renewal_id
    ON payments(renewal_id) WHERE renewal_id IS NOT NULL;

-- Renewal offer expiry tracking.
ALTER TABLE renewals
    ADD COLUMN IF NOT EXISTS offer_expires_at DATE;
ALTER TABLE renewals
    ADD COLUMN IF NOT EXISTS expired_at TIMESTAMPTZ;

-- Backfill expiry for existing renewal rows where the date is not set.
UPDATE renewals r
SET offer_expires_at = LEAST(r.offer_generated_at::date + 30, p.policy_end_date)
FROM policies p
WHERE p.policy_id = r.policy_id
  AND r.offer_expires_at IS NULL;

-- Fail safely rather than inventing an expiry if an unexpected orphan remains.
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM renewals WHERE offer_expires_at IS NULL) THEN
        RAISE EXCEPTION 'Some renewal rows have no offer_expires_at; inspect renewal/policy data before applying NOT NULL.';
    END IF;
END $$;

ALTER TABLE renewals
    ALTER COLUMN offer_expires_at SET NOT NULL;

DO $$ BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'renewals_offer_expiry_check') THEN
        ALTER TABLE renewals ADD CONSTRAINT renewals_offer_expiry_check
            CHECK (offer_expires_at >= offer_generated_at::date);
    END IF;
END $$;


-- Required for document embeddings
CREATE EXTENSION IF NOT EXISTS vector;


-- ============================================================
-- 1. QUOTE RISK ASSESSMENTS
-- ============================================================

CREATE TABLE IF NOT EXISTS quote_risk_assessments (

    assessment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    quote_id VARCHAR(50) NOT NULL
        REFERENCES quotes(quote_id),

    risk_factor_id VARCHAR(50) NOT NULL
        REFERENCES risk_factors(risk_factor_id),

    observed_value JSONB NOT NULL,

    normalized_score NUMERIC(5,2),

    factor_weight NUMERIC(8,4) NOT NULL
        CHECK (factor_weight >= 0),

    weighted_score NUMERIC(10,4)
        CHECK (weighted_score >= 0),

    assessment_reason TEXT NOT NULL,

    assessed_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    ruleset_version VARCHAR(30) NOT NULL,

    CONSTRAINT quote_risk_assessments_normalized_score_check
        CHECK (
            normalized_score >= 0
            AND normalized_score <= 100
        ),

    CONSTRAINT uq_quote_risk_factor
        UNIQUE (quote_id, risk_factor_id)
);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_name = 'quote_risk_assessments'
          AND column_name = 'assessment_id'
          AND is_identity = 'NO'
    ) THEN
        ALTER TABLE quote_risk_assessments
        ALTER COLUMN assessment_id
        ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;
END $$;
-- ============================================================
-- 2. QUOTE RISK OBSERVATIONS
-- ============================================================

CREATE TABLE IF NOT EXISTS quote_risk_observations (
    observation_id BIGINT PRIMARY KEY,

    quote_id VARCHAR(50) NOT NULL
        REFERENCES quotes(quote_id),

    factor_code VARCHAR(100) NOT NULL,

    observed_value JSONB NOT NULL,

    created_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP
);


-- ============================================================
-- 3. UNDERWRITING DOCUMENT CHUNKS
-- ============================================================

CREATE TABLE IF NOT EXISTS underwriting_document_chunks (
    chunk_id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    document_id UUID
        REFERENCES underwriting_documents(document_id)
        ON DELETE CASCADE,

    source_title TEXT NOT NULL,

    chunk_index INTEGER NOT NULL,

    content TEXT NOT NULL,

    embedding VECTOR NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_document_chunk
        UNIQUE (document_id, chunk_index)
);


COMMIT;
